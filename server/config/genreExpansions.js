const UPDATED_AT = '2026-07-10T00:00:00.000Z';

function lore(id, type, title, keywords, content, options = {}) {
  return {
    id,
    type,
    title,
    keywords,
    secondaryKeywords: options.secondaryKeywords || [],
    matchMode: 'keyword',
    regex: options.regex || [],
    logic: options.logic || 'any',
    content,
    priority: options.priority ?? 82,
    depth: options.depth ?? 6,
    insertionOrder: options.insertionOrder ?? 3000,
    constant: options.constant === true,
    caseSensitive: false,
    position: 'after_character',
    scope: 'prompt',
    enabled: true,
    source: 'content-pack',
    extensions: {
      bibleSection: true,
      originalSetting: true,
      ...(options.extensions || {})
    },
    updatedAt: UPDATED_AT
  };
}

function module(id, title, content) {
  return { id, title, enabled: true, content };
}

function routeContractModule(packId, title) {
  const profile = getGenreNarrativeProfile(packId);
  return module(`${packId}-core-route-contract`, title, [
    `固定主线：${profile.activeArc}。`,
    `不得喧宾夺主：${profile.forbiddenDominance.join('；')}。`,
    `回流规则：${profile.routeReturnRule}`,
    '只有用户明确确认更换主线或题材时才可修改；完整支柱与合法辅线由会话叙事路线锁统一注入。'
  ].join('\n'));
}

